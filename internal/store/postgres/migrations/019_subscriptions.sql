CREATE TABLE IF NOT EXISTS subscription_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anchor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    plan_type INTEGER NOT NULL CHECK (plan_type IN (2,3,4)),
    published BOOLEAN NOT NULL DEFAULT TRUE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    price BIGINT NOT NULL CHECK (price >= 0),
    name TEXT NOT NULL DEFAULT '',
    url TEXT NOT NULL DEFAULT '',
    remark TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS subscription_single_free_plan ON subscription_plans (anchor_id) WHERE plan_type=2;
CREATE INDEX IF NOT EXISTS subscription_plans_owner ON subscription_plans (anchor_id, id);

CREATE TABLE IF NOT EXISTS subscription_members (
    fan_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    anchor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    plan_id BIGINT NOT NULL REFERENCES subscription_plans(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    cancelled_at TIMESTAMPTZ,
    reason INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (fan_id, plan_id),
    CHECK (fan_id <> anchor_id)
);

CREATE INDEX IF NOT EXISTS subscription_members_anchor ON subscription_members(anchor_id, fan_id);

CREATE TABLE IF NOT EXISTS subscription_orders (
    order_no TEXT PRIMARY KEY,
    fan_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    plan_id BIGINT NOT NULL REFERENCES subscription_plans(id) ON DELETE RESTRICT,
    points BIGINT NOT NULL CHECK (points > 0),
    status INTEGER NOT NULL DEFAULT 0 CHECK (status IN (0,1,2)),
    provider_order_id BIGINT UNIQUE,
    provider_order_no TEXT UNIQUE,
    provider_points BIGINT,
    provider_bad_debt BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    confirmed_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS subscription_single_pending_purchase ON subscription_orders(fan_id,plan_id) WHERE status=0;

ALTER TABLE dm_conversations ADD COLUMN IF NOT EXISTS subscription_expires_at TIMESTAMPTZ;
