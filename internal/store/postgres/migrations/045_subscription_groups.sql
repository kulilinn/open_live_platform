CREATE TABLE subscription_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind SMALLINT NOT NULL CHECK (kind BETWEEN 0 AND 3),
    name TEXT NOT NULL
);
CREATE UNIQUE INDEX subscription_group_defaults ON subscription_groups (owner_id,kind) WHERE kind<3;
CREATE INDEX subscription_group_owner ON subscription_groups (owner_id,id);

CREATE TABLE subscription_group_members (
    group_id BIGINT NOT NULL REFERENCES subscription_groups(id) ON DELETE CASCADE,
    person_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    added_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    PRIMARY KEY (group_id,person_id)
);

CREATE TABLE subscription_saved_users (
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    person_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind SMALLINT NOT NULL CHECK (kind IN (2,3)),
    PRIMARY KEY (owner_id,person_id,kind),
    CHECK (owner_id<>person_id)
);
