CREATE TABLE anchor_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    visibility SMALLINT NOT NULL CHECK (visibility BETWEEN 0 AND 4),
    price BIGINT NOT NULL CHECK (price >= 0),
    media JSONB NOT NULL,
    only_text SMALLINT NOT NULL CHECK (only_text IN (0,1)),
    images INTEGER NOT NULL CHECK (images >= 0),
    videos INTEGER NOT NULL CHECK (videos >= 0),
    video_length INTEGER NOT NULL CHECK (video_length >= 0),
    reference_post TEXT NOT NULL,
    status SMALLINT NOT NULL CHECK (status IN (1,2,3)),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at TIMESTAMPTZ,
    like_count BIGINT NOT NULL DEFAULT 0 CHECK (like_count >= 0),
    comment_count BIGINT NOT NULL DEFAULT 0 CHECK (comment_count >= 0),
    tip_points BIGINT NOT NULL DEFAULT 0 CHECK (tip_points >= 0)
);

CREATE INDEX anchor_posts_pub ON anchor_posts (created_at DESC,id DESC) WHERE status=3 AND NOT deleted AND visibility<>1;
CREATE INDEX anchor_posts_owner ON anchor_posts (owner_id,id DESC) WHERE NOT deleted;

CREATE TABLE anchor_post_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES anchor_posts(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    parent_id BIGINT,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    like_count BIGINT NOT NULL DEFAULT 0 CHECK (like_count >= 0),
    UNIQUE (post_id,id),
    FOREIGN KEY (post_id,parent_id) REFERENCES anchor_post_comments(post_id,id) ON DELETE CASCADE
);

CREATE INDEX anchor_post_comments_parent ON anchor_post_comments (post_id,parent_id) WHERE NOT deleted;

CREATE TABLE anchor_post_likes (
    post_id BIGINT NOT NULL REFERENCES anchor_posts(id) ON DELETE CASCADE,
    actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (post_id,actor_id)
);

CREATE TABLE anchor_post_comment_likes (
    comment_id BIGINT NOT NULL REFERENCES anchor_post_comments(id) ON DELETE CASCADE,
    actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (comment_id,actor_id)
);
