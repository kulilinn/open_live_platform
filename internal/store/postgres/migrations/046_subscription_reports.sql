CREATE TABLE subscription_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    person_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    post_id BIGINT REFERENCES anchor_posts(id) ON DELETE SET NULL,
    kind SMALLINT NOT NULL CHECK (kind BETWEEN 1 AND 5),
    urls TEXT[] NOT NULL,
    remark TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp()
);
CREATE INDEX subscription_report_created ON subscription_reports (created_at,id);
