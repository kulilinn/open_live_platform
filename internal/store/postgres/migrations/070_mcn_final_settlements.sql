CREATE TABLE mcn_final_settlements (
    trace_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membership_id BIGINT NOT NULL REFERENCES backoffice_mcn_streamers(id) ON DELETE RESTRICT,
    agency_id BIGINT NOT NULL CHECK(agency_id>0),
    streamer_id BIGINT NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ NOT NULL CHECK(confirmed_at>=joined_at),
    gross_ld BIGINT NOT NULL CHECK(gross_ld>=0),
    bad_debt_ld BIGINT NOT NULL CHECK(bad_debt_ld BETWEEN 0 AND gross_ld),
    UNIQUE(membership_id,joined_at)
);

CREATE TABLE mcn_final_settlement_items (
    trace_id BIGINT NOT NULL REFERENCES mcn_final_settlements(trace_id) ON DELETE RESTRICT,
    source TEXT NOT NULL,
    source_id TEXT NOT NULL,
    payment_group TEXT NOT NULL,
    provider_order_id BIGINT NOT NULL CHECK(provider_order_id>0),
    provider_order_no TEXT NOT NULL CHECK(provider_order_no<>''),
    confirmed_points BIGINT NOT NULL CHECK(confirmed_points>0),
    gross_ld BIGINT NOT NULL CHECK(gross_ld>=0),
    bad_debt_ld BIGINT NOT NULL CHECK(bad_debt_ld BETWEEN 0 AND gross_ld),
    paid_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY(source,source_id)
);
CREATE INDEX mcn_final_receipt_idx ON mcn_final_settlement_items(provider_order_id);
CREATE INDEX mcn_final_trace_idx ON mcn_final_settlement_items(trace_id);

CREATE TABLE mcn_legacy_settlement_proofs (
    settlement_id BIGINT PRIMARY KEY CHECK(settlement_id>0),
    agency_id BIGINT NOT NULL CHECK(agency_id>0),
    streamer_id BIGINT NOT NULL CHECK(streamer_id>0),
    provider_order_id BIGINT,
    provider_order_no TEXT,
    charged BIGINT CHECK(charged>0),
    gross_ld BIGINT NOT NULL CHECK(gross_ld>=0),
    bad_debt_ld BIGINT NOT NULL CHECK(bad_debt_ld BETWEEN 0 AND gross_ld),
    provider_verified BOOLEAN NOT NULL,
    source_pending BOOLEAN NOT NULL,
    paid_at TIMESTAMPTZ NOT NULL,
    CHECK(NOT provider_verified OR (provider_order_id>0 AND provider_order_id IS NOT NULL
        AND provider_order_no IS NOT NULL AND provider_order_no<>'' AND charged IS NOT NULL))
);
CREATE INDEX mcn_legacy_settlement_lookup_idx ON mcn_legacy_settlement_proofs(agency_id,streamer_id,paid_at) WHERE source_pending;
