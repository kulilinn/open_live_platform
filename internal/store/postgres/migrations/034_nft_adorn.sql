CREATE TABLE nft_challenges (
    id BIGINT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    message TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX nft_challenge_expiry_idx ON nft_challenges(expires_at);

CREATE TABLE nft_bindings (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    token_id BIGINT NOT NULL UNIQUE CHECK (token_id BETWEEN 0 AND 4294967295),
    address TEXT NOT NULL CHECK (address ~ '^0x[0-9a-f]{40}$')
);

CREATE TABLE nft_binding_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_id BIGINT NOT NULL,
    address TEXT NOT NULL,
    bound BOOLEAN NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp()
);
CREATE INDEX nft_binding_history_user_idx ON nft_binding_events(user_id);
CREATE INDEX nft_binding_history_token_idx ON nft_binding_events(token_id);

CREATE TABLE nft_equipped_adorn (
    user_id BIGINT NOT NULL REFERENCES nft_bindings(user_id) ON DELETE CASCADE,
    slot SMALLINT NOT NULL CHECK (slot BETWEEN 1 AND 7),
    adorn_id INTEGER NOT NULL CHECK (adorn_id > 0),
    PRIMARY KEY(user_id, slot)
);
